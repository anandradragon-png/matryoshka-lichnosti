/* Самый «согласный» ответ. Отсюда считается и максимум шкалы, и балл обратного
   утверждения (`TOP − выбранное`), поэтому значение живёт в одном месте: две
   копии максимума — это два разных результата теста при правке шкалы ответов. */
export const TOP = Math.max(...ANSWERS.map(a => a.value));

/* Сколько баллов даёт шкала целиком и где её середина. Считается из данных,
   а не проставлено числом: добавят вопрос — порог сдвинется сам. */
export function scaleMax(scaleId) {
  return QUESTIONS.filter(q => q.s === scaleId).length * TOP;
}

