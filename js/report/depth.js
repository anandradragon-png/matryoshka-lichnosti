/* ================= ОТЧЁТ: ГЛУБИНА РАЗБОРА =================
   Тариф больше НЕ решает, какие разделы попадут в отчёт. Разделы одинаковые
   у всех: настроение, что заметно, практики, Дар, разговоры, что делать
   дальше. Тариф решает только одно — насколько подробно каждый разобран.

   ПОЧЕМУ ТАК. Раньше бесплатный отчёт был огрызком: две таблицы и список
   «что вам не отдали». Человек видел не свой отчёт, а витрину. Теперь он
   получает отчёт целиком — просто короткий. Что покупают за деньги, видно
   сразу: те же разделы, разобранные глубже.

   ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ plan.js. plan.js отвечает на вопрос «есть ли
   доступ», здесь — «насколько подробно». Это разные вопросы: если завтра
   появится четвёртый уровень подробности или выбор глубины руками, plan.js
   об этом знать не должен. */
import { getPlan, PLAN_ORDER } from '../plan.js';

/* Уровни. Числа сравниваются (depth >= 2), поэтому порядок важен. */
export const BRIEF = 1;    // 1–2 страницы: коротко, но целиком
export const NORMAL = 2;   // 5–7 страниц: с таблицами и разбором
export const FULL = 3;     // 10–12 страниц: со всем, что вообще известно

const BY_PLAN = { free: BRIEF, standard: NORMAL, premium: FULL };

/* Сколько страниц обещаем — этим же текстом объясняем разницу тарифов
   и в самом отчёте, и в окне выбора периода. Обещание должно совпадать
   с тем, что человек получит, иначе это обман. */
export const DEPTH_PAGES = { [BRIEF]: '1–2 страницы', [NORMAL]: '5–7 страниц', [FULL]: '10–12 страниц' };

export const DEPTH_LABEL = {
  [BRIEF]: 'краткий разбор',
  [NORMAL]: 'подробный разбор',
  [FULL]: 'полный разбор',
};

/* Неизвестный тариф — самый короткий отчёт, а не пустота: из-за опечатки
   в хранилище человек не должен остаться без отчёта совсем. */
export function depthFor(plan = getPlan()) {
  return BY_PLAN[PLAN_ORDER.includes(plan) ? plan : 'free'] || BRIEF;
}

/* Что человек получит, если поднимет тариф. Пусто — он уже на полном
   разборе, и уговаривать его не надо. */
export function deeperThan(depth) {
  if (depth >= FULL) return null;
  const next = depth + 1;
  return { depth: next, pages: DEPTH_PAGES[next], label: DEPTH_LABEL[next] };
}
