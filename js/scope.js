/* ================= ЧЬИ ЭТО ДАННЫЕ =================
   Дневник и журнал дня раньше лежали в одном ключе на весь браузер. Если за
   одним компьютером сидят два человека, второй видел записи первого — и в
   отчёт попадали чужие эмоции. Эмоции — специальная категория персональных
   данных, так быть не должно.

   Теперь ключ зависит от того, кто вошёл: `ml_diary__sveta`, `ml_diary__anna`.

   ЭТО РАЗДЕЛЕНИЕ, А НЕ ЗАЩИТА. Пароли всё ещё лежат в браузере, и кто угодно
   может открыть инструменты разработчика и прочитать чужой ключ руками.
   Настоящая защита появится только вместе с сервером: пароль хешируется там,
   данные отдаются по токену. До тех пор эта функция решает ровно одну задачу —
   чтобы люди не путались в чужих записях случайно.

   Гость (никто не вошёл) работает со старым общим ключом. Первый, кто войдёт,
   забирает накопленное себе: данные должны лежать в одном месте, две копии —
   это две правды, и непонятно, какая настоящая. */
import { ML_KEYS } from './core.js';

export const currentLogin = () => localStorage.getItem(ML_KEYS.session) || '';

/* Ключ данных текущего пользователя. Заодно однократно переносит накопленное
   гостем: человек, который завёл кабинет, не должен потерять свой дневник. */
export function scopedKey(base) {
  const login = currentLogin();
  if (!login) return base;
  const key = base + '__' + login;
  const legacy = localStorage.getItem(base);
  if (legacy !== null) {
    if (localStorage.getItem(key) === null) localStorage.setItem(key, legacy);
    localStorage.removeItem(base);
  }
  return key;
}

/* Сообщить приложению, что пользователь сменился: дневник, статистика и
   журнал на экране принадлежат другому человеку и должны перерисоваться. */
export const announceSessionChange = () =>
  document.dispatchEvent(new CustomEvent('ml:session'));
