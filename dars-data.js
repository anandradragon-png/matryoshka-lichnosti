/* --- Расчёт кода Дара по дате рождения (calculator.py) --- */
function reduceDigit(v){ while(v>9){ v=String(v).split('').reduce((a,c)=>a+ +c,0);} return v===0?9:v; }
function sumDigits(n){ return String(Math.abs(n)).split('').reduce((a,c)=>a+ +c,0); }

function calculateDar(day, month, year){
  const ma  = reduceDigit(sumDigits(day) + sumDigits(month)); // МА — магия/потенциал
  const zhi = reduceDigit(sumDigits(year));                   // ЖИ — жизнь/реализация
  const kun = reduceDigit(ma + zhi);                          // КУН — мощность/результат
  return { code:`${ma}-${zhi}-${kun}`, ma, zhi, kun };
}

/* Тип особого дара */
function detectType(ma, zhi){
  if(ma===9 && zhi===9) return 'absolute';       // 9-9-9
  if(zhi===9 && ma!==9) return 'field_human';    // человек-поле
  if(ma===9  && zhi!==9) return 'field_human';
  return 'standard';
}

/* Полный результат для UI: дар + описание поля (по КУН) */
function getPersonalityCard(day, month, year){
  const { code, ma, zhi, kun } = calculateDar(day, month, year);
  const dar = DARS[code] || ["НЕИЗВЕСТНЫЙ ДАР","Уникальное сочетание"];
  const field = FIELDS[kun] || FIELDS[9];
  return {
    code, ma, zhi, kun,
    darName: dar[0], darArch: dar[1],
    field, type: detectType(ma, zhi),
    fieldMa: FIELDS[ma], fieldZhi: FIELDS[zhi], fieldKun: FIELDS[kun],
  };
}

